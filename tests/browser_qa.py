import json
import os
from pathlib import Path
from playwright.sync_api import sync_playwright

ROOT = Path(__file__).resolve().parent.parent
OUT = Path('/tmp/spaceswap-qa-results')
OUT.mkdir(exist_ok=True)

with sync_playwright() as pw:
    browser = pw.chromium.launch(executable_path=os.environ.get('CHROME_PATH', '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'), headless=True, args=['--use-angle=swiftshader', '--enable-unsafe-swiftshader'])
    page = browser.new_page(viewport={'width': 1512, 'height': 982}, device_scale_factor=1)
    errors = []
    page.on('pageerror', lambda error: errors.append(str(error)))
    base_url = os.environ.get('SPACESWAP_URL', 'http://127.0.0.1:5173')
    page.goto(base_url + '/#editor', wait_until='networkidle')
    page.screenshot(path=str(OUT/'editor-initial.png'), full_page=True)
    print('TITLE', page.title(), flush=True)
    print('ERRORS', errors, flush=True)
    results = page.evaluate("""async () => {const t=await import('/tests/core.test.js'); return t.runCoreTests();}""")
    print('CORE TESTS', len(results), json.dumps(results), flush=True)
    checks = []
    def check(name, condition):
        assert condition, name
        checks.append(name)
        print('PASS', name, flush=True)
    def state(expression):
        return page.evaluate('() => ' + expression)
    # Real pointer dragging must change shared geometry and show a conflict.
    sofa = page.locator('[data-furniture="a-sofa"]')
    coffee = page.locator('[data-furniture="a-coffee"]')
    sb, cb = sofa.bounding_box(), coffee.bounding_box()
    old = state('({...spaceSwap.activeApartment().furniture.find(f=>f.id==="a-sofa")})')
    page.mouse.move(sb['x']+sb['width']/2, sb['y']+sb['height']/2)
    page.mouse.down()
    page.mouse.move(cb['x']+cb['width']/2, cb['y']+cb['height']/2, steps=12)
    page.mouse.up()
    check('Pointer drag updates furniture position', state('spaceSwap.activeApartment().furniture.find(f=>f.id==="a-sofa").z') != old['z'])
    check('Drag creates an actual overlap warning', state('spaceSwap.analyze(spaceSwap.activeApartment(),spaceSwap.store.get().preferences).some(i=>i.kind==="overlap"&&i.itemId==="a-sofa")'))
    page.locator('[data-action="undo"]').click()
    check('Undo restores position and removes overlap', state('spaceSwap.activeApartment().furniture.find(f=>f.id==="a-sofa").z') == old['z'] and not state('spaceSwap.analyze(spaceSwap.activeApartment(),spaceSwap.store.get().preferences).some(i=>i.kind==="overlap"&&i.itemId==="a-sofa")'))
    page.locator('[data-furniture="a-desk"]').click()
    page.locator('[data-action="rotate"]').click()
    check('Rotate button changes shared orientation', state('spaceSwap.activeApartment().furniture.find(f=>f.id==="a-desk").rotation') == 90)
    page.locator('[data-property="width"]').fill('1.55')
    page.locator('[data-property="width"]').press('Tab')
    check('Owned dimensions propagate across apartments', state('spaceSwap.store.get().apartments.every(a=>a.furniture.find(f=>f.inventoryId==="inv-desk").width===1.55)'))
    page.locator('[data-action="mode"][data-mode="3d"]').first.click()
    page.wait_for_function('spaceSwap.scene && spaceSwap.scene.renderer.info.render.calls > 0', timeout=30000)
    page.wait_for_timeout(1200)
    page.screenshot(path=str(OUT/'editor-3d.png'), full_page=True)
    check('3D renders actual triangle geometry', state('spaceSwap.scene.renderer.info.render.triangles') > 100)
    check('3D uses edited shared furniture dimensions', state('spaceSwap.scene.options.apartment().furniture.find(f=>f.id==="a-desk").width') == 1.55)
    check('3D furniture rotation matches shared state', abs(state('spaceSwap.scene.model.children.find(g=>g.userData.furnitureId==="a-desk").rotation.y') + 3.141592653589793/2) < 1e-8)
    # Numeric 3D editing updates actual rendered transform.
    page.locator('[data-property="x"]').fill('2.2')
    page.locator('[data-property="x"]').press('Tab')
    page.wait_for_function('spaceSwap.scene && spaceSwap.scene.renderer.info.render.calls > 0')
    check('3D inspector updates mesh position', state('spaceSwap.scene.model.children.find(g=>g.userData.furnitureId==="a-desk").position.x') == 2.2)
    # Room edit rebuilds floor geometry.
    page.locator('[data-action="library-tab"][data-tab="rooms"]').click()
    page.locator('[data-action="select"][data-id="a-bath"]').click()
    page.locator('[data-property="width"]').fill('4.2')
    page.locator('[data-property="width"]').press('Tab')
    page.wait_for_function('spaceSwap.scene && spaceSwap.scene.renderer.info.render.calls > 0')
    check('Room resize updates 3D floor geometry', state('spaceSwap.scene.architecture.children.some(m=>m.geometry?.parameters?.width===4.2 && m.geometry?.parameters?.height===.12)'))
    page.locator('[data-action="mode"][data-mode="2d"]').click()
    check('Switching to 2D retains edits', state('spaceSwap.activeApartment().furniture.find(f=>f.id==="a-desk").x') == 2.2)
    page.reload(wait_until='domcontentloaded')
    page.wait_for_selector('.floor-svg')
    check('Refresh restores saved dimensions and position', state('spaceSwap.activeApartment().rooms.find(r=>r.id==="a-bath").width') == 4.2 and state('spaceSwap.activeApartment().furniture.find(f=>f.id==="a-desk").x') == 2.2)
    count = state('spaceSwap.activeApartment().furniture.length')
    page.locator('[data-action="add-catalog"][data-id="lamp"]').click()
    check('Catalog adds a real furniture instance', state('spaceSwap.activeApartment().furniture.length') == count+1)
    page.locator('[data-action="delete"]').click()
    check('Delete removes the added instance', state('spaceSwap.activeApartment().furniture.length') == count)
    page.locator('[data-action="custom-furniture"]').click()
    page.locator('dialog input[name="name"]').fill('My custom ottoman')
    page.locator('dialog input[name="width"]').fill('0.7')
    page.locator('dialog input[name="depth"]').fill('0.7')
    page.locator('dialog input[name="height"]').fill('0.4')
    page.locator('dialog button[type="submit"]').click()
    check('Manual furniture entry works', state('spaceSwap.activeApartment().furniture.some(f=>f.name==="My custom ottoman"&&f.width===.7)'))
    page.locator('[data-action="navigate"][data-page="compare"]').first.click()
    page.wait_for_selector('.comparison-card')
    check('Both apartment comparisons render', page.locator('.comparison-card').count() == 2)
    page.locator('[data-preference="months"]').fill('24')
    page.locator('[data-preference="months"]').press('Tab')
    check('Length of stay updates live totals', state('spaceSwap.store.get().preferences.months') == 24 and '24-MONTH' in page.locator('.total-cost').first.inner_text())
    page.locator('[data-cost="rent"][data-apartment="willow"]').fill('')
    page.locator('[data-cost="rent"][data-apartment="willow"]').press('Tab')
    check('Missing cost is marked incomplete', 'Incomplete' in page.locator('.comparison-card').first.inner_text())
    check('Missing cost withholds the winner badge', 'best match' not in page.locator('.comparison-grid').inner_text())
    page.locator('[data-action="report"]').click()
    check('Missing cost withholds the report recommendation', 'Complete your costs before choosing a winner.' in page.locator('.report-document').inner_text())
    page.locator('[data-action="navigate"][data-page="compare"]').first.click()
    page.locator('[data-cost="rent"][data-apartment="willow"]').fill('2450')
    page.locator('[data-cost="rent"][data-apartment="willow"]').press('Tab')
    page.screenshot(path=str(OUT/'comparison.png'), full_page=True)
    page.locator('[data-action="report"]').click()
    check('Report reflects edited stay length', '24-month total' in page.locator('.report-document').inner_text())
    check('Report includes actual custom furniture costs', 'The Willow Loft' in page.locator('.report-document').inner_text())
    page.pdf(path=str(OUT/'decision-report.pdf'), format='A4', print_background=True)
    check('Printable PDF generated', (OUT/'decision-report.pdf').stat().st_size > 10000)
    page.locator('[data-action="navigate"][data-page="inventory"]').click()
    page.locator('[data-action="custom-inventory"]').first.click()
    page.locator('dialog input[name="name"]').fill('Personal cabinet')
    page.locator('dialog button[type="submit"]').click()
    check('Personal inventory entry works', state('spaceSwap.store.get().inventory.some(i=>i.name==="Personal cabinet")'))
    page.locator('.inventory-card').filter(has_text='Personal cabinet').locator('[data-action="place-both"]').click()
    check('Same inventory item placed in both apartments', state('spaceSwap.store.get().apartments.every(a=>a.furniture.some(f=>f.name==="Personal cabinet"))'))
    # Navigation and mobile layout, including no horizontal overflow.
    page.locator('[data-action="navigate"][data-page="overview"]').click()
    check('Overview uses live project data', page.locator('.space-card').count() == 2)
    page.locator('[data-action="navigate"][data-page="settings"]').click()
    page.locator('[data-setting="units"]').select_option('imperial')
    page.locator('[data-action="navigate"][data-page="editor"]').first.click()
    check('Imperial units rendered in editor', 'ft²' in page.locator('.editor-heading').inner_text())
    page.set_viewport_size({'width': 390, 'height': 844})
    page.screenshot(path=str(OUT/'mobile.png'), full_page=True)
    check('Mobile editor has no horizontal overflow', state('document.documentElement.scrollWidth') <= 390)
    page.locator('[data-action="menu"]').click()
    page.locator('.sidebar [data-action="navigate"][data-page="compare"]').first.click()
    check('Mobile navigation opens comparison', page.locator('.comparison-card').count() == 2)
    check('Mobile comparison has no horizontal overflow', state('document.documentElement.scrollWidth') <= 390)
    page.screenshot(path=str(OUT/'comparison-mobile.png'), full_page=True)
    page.goto(base_url+'/#landing', wait_until='domcontentloaded')
    check('Landing page CTA works', page.locator('.landing').count() == 1)
    check('Mobile landing has no horizontal overflow', state('document.documentElement.scrollWidth') <= 390)
    page.screenshot(path=str(OUT/'landing-mobile.png'), full_page=True)
    check('No browser runtime exceptions', not errors)
    print('BROWSER CHECKS', len(checks), json.dumps(checks), flush=True)
    (OUT/'results.json').write_text(json.dumps({'core':results,'browser':checks,'errors':errors},indent=2))
    browser.close()
